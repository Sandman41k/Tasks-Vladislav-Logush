package library.block_2_2.task_2;

public class Puzzle {
    public static void main(String[] args) {
        int a = 5;

        // b = 5, а становится 6 (постфиксный инкремент: сначала берем 5, потом увеличиваем a)
        int b = a++;

        // c = 7, а становится 7 (префиксный инкремент: сначала увеличиваем а до 7, потом берем)
        int c = ++a;

        // d = 7 + 4 = 11. Переменная а становится 6. Переменная b становится 4.
        // (a-- вернуло 7, а --b сначала уменьшило b с 5 до 4 и вернуло 4)
        int d = a-- + --b;

        // Ожидаемый вывод: 6 4 7 11
        System.out.println(a + " " + b + " " + c + " " + d);
    }
}

